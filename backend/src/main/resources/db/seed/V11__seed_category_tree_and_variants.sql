-- Sản phẩm áp dụng: còn đúng 1 biến thể mặc định, chưa có tuỳ chọn
CREATE TEMP TABLE variant_target ON COMMIT DROP AS
SELECT p.id AS product_id, p.stock_quantity, s.*,
       cardinality(s.values1) * COALESCE(cardinality(s.values2), 1) AS n
FROM variant_seed s
JOIN products p ON p.slug = s.product_slug
WHERE NOT EXISTS (SELECT 1 FROM product_options o WHERE o.product_id = p.id)
  AND (SELECT count(*) FROM product_variants v WHERE v.product_id = p.id AND v.option1_value_id IS NULL) = 1
  AND (SELECT count(*) FROM product_variants v WHERE v.product_id = p.id) = 1;

-- 1. Tuỳ chọn (vị trí 1, 2) và giá trị (vị trí từ 0)
INSERT INTO product_options (product_id, name, position)
SELECT product_id, option1, 1 FROM variant_target
UNION ALL
SELECT product_id, option2, 2 FROM variant_target WHERE option2 IS NOT NULL;

INSERT INTO product_option_values (option_id, value, position)
SELECT o.id, v.value, v.ord - 1
FROM variant_target t
JOIN product_options o ON o.product_id = t.product_id
CROSS JOIN LATERAL unnest(CASE o.position WHEN 1 THEN t.values1 ELSE t.values2 END) WITH ORDINALITY AS v(value, ord);

-- 2. Mọi tổ hợp, thứ tự như admin sinh (giá trị tuỳ chọn 1 trước, rồi tuỳ chọn 2); chia đều tồn kho
CREATE TEMP TABLE variant_combo ON COMMIT DROP AS
SELECT c.product_id, c.v1, c.v2, c.idx,
       c.stock_quantity / c.n + CASE WHEN c.idx < c.stock_quantity % c.n THEN 1 ELSE 0 END AS stock
FROM (
    SELECT t.product_id, t.stock_quantity, t.n, a.id AS v1, b.id AS v2,
           (row_number() OVER (PARTITION BY t.product_id ORDER BY a.position, b.position NULLS FIRST) - 1)::INT AS idx
    FROM variant_target t
    JOIN product_options o1 ON o1.product_id = t.product_id AND o1.position = 1
    JOIN product_option_values a ON a.option_id = o1.id
    LEFT JOIN product_options o2 ON o2.product_id = t.product_id AND o2.position = 2
    LEFT JOIN product_option_values b ON b.option_id = o2.id
) c;

-- 3. Biến thể mặc định → tổ hợp đầu tiên (giữ id); thêm các tổ hợp còn lại
UPDATE product_variants pv
SET option1_value_id = c.v1, option2_value_id = c.v2, stock_quantity = c.stock, position = 0, updated_at = now()
FROM variant_combo c
WHERE c.idx = 0 AND pv.product_id = c.product_id;

INSERT INTO product_variants (product_id, option1_value_id, option2_value_id, stock_quantity, is_active, position,
                              created_at, updated_at)
SELECT product_id, v1, v2, stock, TRUE, idx, now(), now()
FROM variant_combo
WHERE idx > 0;

UPDATE products p SET updated_at = now() FROM variant_target t WHERE p.id = t.product_id;

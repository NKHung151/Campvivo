CREATE TEMP TABLE category_target ON COMMIT DROP AS
SELECT c.id AS old_id,
       (SELECT m.new_slug FROM category_map m JOIN categories a ON a.id = m.old_id
         WHERE c.path LIKE a.path || '%' ORDER BY length(a.path) DESC LIMIT 1) AS new_slug
FROM categories c WHERE c.slug LIKE 'old-%';
UPDATE category_target SET new_slug = 'phu-kien-da-ngoai' WHERE new_slug IS NULL;

-- 4. Sản phẩm Xe Máy / Ô Tô: chưa ai dùng thì xoá (ảnh, biến thể, khuyến mãi, đánh giá xoá theo); đã dùng thì ẩn
DELETE FROM products p
USING category_target t
WHERE p.category_id = t.old_id AND t.new_slug = 'REMOVED'
  AND NOT EXISTS (SELECT 1 FROM order_items x WHERE x.product_id = p.id)
  AND NOT EXISTS (SELECT 1 FROM cart_items x WHERE x.product_id = p.id)
  AND NOT EXISTS (SELECT 1 FROM combo_items x WHERE x.product_id = p.id)
  AND NOT EXISTS (SELECT 1 FROM inventory_logs x WHERE x.product_id = p.id);
UPDATE products p SET is_active = FALSE, updated_at = now()
FROM category_target t WHERE p.category_id = t.old_id AND t.new_slug = 'REMOVED';
UPDATE category_target SET new_slug = 'phu-kien-da-ngoai' WHERE new_slug = 'REMOVED';

